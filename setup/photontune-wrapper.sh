#!/bin/sh
# photontune - run the tuner, log it locally, and say one line about it.
#
# Installed by photonvision-tools (setup/install_photontune_status.sh).
#
# TWO PROBLEMS THIS SOLVES
#
# 1. Nothing was recorded. photontune writes no logfile and journald captures
#    only the SERVICE's output, so a tune somebody ran by hand printed to their
#    terminal and was recorded nowhere. Ask afterwards what the cameras were
#    set to and the honest answer was "nobody knows". Not good enough for
#    something a match depends on. Every run now appends a timestamped copy to
#    /var/log/photontune/photontune.log, which photontune-status reads.
#
# 2. The tuner's own output is ~100 lines of gain-walk detail. Correct, and
#    nobody in a pit reads it. So by default this prints the SAME one line
#    photontune-status prints - generated by photontune-status itself, not
#    reimplemented here, so the two can never disagree about wording.
#
#     photontune           # tune, log it, print one line
#     photontune -v        # ...and show the tuner's output as it goes
#     photontune -vvv      # ...and the full status report afterwards
#     photontune --help    # the tuner's own options
#
# Everything that is not -v/-vv/-vvv is passed straight through to the tuner.
set -e

# Overridable so the logging path can be tested against a stub tuner without
# touching a camera. A test that needs real hardware is a test nobody runs.
TUNER="${PHOTONTUNE_TUNER:-/opt/photontune/photontune.py}"
STATUS="${PHOTONTUNE_STATUS:-/opt/photontune/photontune_status.py}"
LOGDIR="${PHOTONTUNE_LOGDIR:-/var/log/photontune}"
LOG="$LOGDIR/photontune.log"

if [ ! -f "$TUNER" ]; then
    echo "photontune is not installed at $TUNER" >&2
    exit 1
fi

# Strip our own verbosity flags; everything else belongs to the tuner.
V=0
ARGS=""
for a in "$@"; do
    case "$a" in
        -h|--help|--explain) exec /usr/bin/python3 "$TUNER" "$@" ;;
        -v)   V=1 ;;
        -vv)  V=2 ;;
        -vvv) V=3 ;;
        *)    ARGS="$ARGS $a" ;;
    esac
done

if ! mkdir -p "$LOGDIR" 2>/dev/null; then
    sudo mkdir -p "$LOGDIR" && sudo chown "$(id -un)" "$LOGDIR"
fi
if [ ! -w "$LOGDIR" ]; then
    echo "cannot write $LOGDIR - run:  sudo chown $(id -un) $LOGDIR" >&2
    exit 1
fi

# One banner per run so photontune-status can find where this run begins. The
# journal gets "Started photontune.service" for free; a manual run needs this.
STAMP=$(date -u +%Y-%m-%dT%H:%M:%S+0000)
printf '%s photontune manual run started:%s\n' "$STAMP" "$ARGS" >> "$LOG"

[ "$V" -eq 0 ] && echo "tuning... (~45 s; -v to watch, log in $LOG)"

# Timestamp every line into the log, and echo to the terminal only when asked.
# python3 rather than awk because mawk - what is actually on the Pi - has no
# strftime, and rather than `ts`, which lives in moreutils and is not here.
#
# The tuner's exit status is carried through the pipe deliberately: /bin/sh has
# no pipefail, so without this a failed tune behind a successful prefixer would
# look like success, and the log would record a tune that passed when it did not.
set +e
{
    /usr/bin/python3 -u "$TUNER" $ARGS 2>&1
    echo "__PHOTONTUNE_EXIT_$?__"
} | /usr/bin/python3 -u -c '
import datetime, re, sys
log, echo = sys.argv[1], sys.argv[2] == "1"
code = 0
with open(log, "a") as fh:
    for line in sys.stdin:
        hit = re.match(r"__PHOTONTUNE_EXIT_(\d+)__", line.strip())
        if hit:
            code = int(hit.group(1))
            continue
        now = datetime.datetime.now(datetime.timezone.utc).strftime(
            "%Y-%m-%dT%H:%M:%S+0000")
        if echo:
            sys.stdout.write(line)
            sys.stdout.flush()
        fh.write("%s %s" % (now, line if line.endswith("\n") else line + "\n"))
        fh.flush()
    now = datetime.datetime.now(datetime.timezone.utc).strftime(
        "%Y-%m-%dT%H:%M:%S+0000")
    fh.write("%s photontune manual run finished: exit=%d\n" % (now, code))
sys.exit(code)
' "$LOG" "$([ "$V" -ge 1 ] && echo 1 || echo 0)"
TUNE_EXIT=$?
set -e

# The one line, from photontune-status itself so the wording cannot drift.
echo ""
if [ "$V" -ge 3 ] && [ -f "$STATUS" ]; then
    /usr/bin/python3 "$STATUS" -v
elif [ -f "$STATUS" ]; then
    /usr/bin/python3 "$STATUS"
else
    echo "photontune exit=$TUNE_EXIT  (photontune_status not installed)"
fi
STATUS_EXIT=$?

# A tuner that failed is the louder fact; otherwise defer to the status verdict.
[ "$TUNE_EXIT" -ne 0 ] && exit "$TUNE_EXIT"
exit "$STATUS_EXIT"
